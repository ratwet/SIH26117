class NetworkStats(BaseModel):
    """Real-time network socket telemetry proving zero outbound WAN bytes."""
    timestamp: str
    wan_interface: str = Field(default="eth0/wlan0")
    total_rx_bytes: int
    total_tx_bytes: int
    outbound_wan_bytes_delta: int = Field(
        default=0,
        description="Must be exactly 0 during demo to prove air-gap compliance."
    )
    air_gap_status: str = Field(default="LOCKED_AIR_GAP_COMPLIANT")
    is_air_gapped: bool = Field(
        default=True,
        description="True if completely air-gapped without external WAN leak, False otherwise."
    )
    external_gateway_detected: bool = Field(
        default=False,
        description="True if a default gateway or WAN route is detected."
    )
    active_local_connections: int = Field(
        default=1,
        description="Active local network socket connections (LAN/localhost)."
    )


class AuditEvent(BaseModel):
    """A single append-only cryptographic transaction for the audit chain."""
    event_id: Optional[str] = None
    timestamp: Optional[str] = None
    user_role: str = Field(..., json_schema_extra={"example": "senior_engineer"})
    model_id: str = Field(..., json_schema_extra={"example": "deepseek-r1:8b"})
    task_type: str = Field(..., json_schema_extra={"example": "api_570_calculation"})
    prompt_hash: str = Field(..., description="SHA-256 hash of input prompt/data.")
    tool_exit_code: int = Field(default=0)
    output_hash: str = Field(..., description="SHA-256 hash of output result.")
    previous_hash: Optional[str] = Field(default=None, description="SHA-256 hash of previous audit log row.")
    entry_hash: Optional[str] = Field(default=None, description="SHA-256 hash of this complete row.")
