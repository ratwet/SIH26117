class SandboxExecutionRequest(BaseModel):
    """Input payload to execute code in the isolated sandbox."""
    code: str = Field(..., description="The raw Python script generated by the LLM.")
    timeout_seconds: int = Field(default=5, description="Execution timeout cap.")
    memory_limit_mb: int = Field(default=256, description="RAM limit for the sandbox process.")


class SandboxResult(BaseModel):
    """Output returned by the sandbox execution runner."""
    success: bool = Field(..., description="True if script exited with code 0.")
    exit_code: int = Field(..., description="Process exit code (0 = success, non-zero = failure).")
    stdout: str = Field(default="", description="Captured standard output.")
    stderr: str = Field(default="", description="Captured raw standard error.")
    distilled_error: Optional[str] = Field(
        default=None,
        description="Clean 2-line root cause summary parsed from stderr, used for LLM self-healing."
    )
    parsed_output: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured JSON/dict parsed from stdout (e.g. remaining_life, corrosion_rate)."
    )


